#!/usr/bin/env bash
# Export the build and the patch stack to the OE android-tools recipe.
#
# usage: scripts/export-oe-patches.sh <recipe-dir>
#
# <recipe-dir> holds android-tools_<ver>.bb, which fetches the AOSP projects
# itself (AOSP_TAG, AOSP_PROJECTS; see the layer's aosp-projects.bbclass).
# This replaces <recipe-dir>/android-tools/build/ with build/ and
# <recipe-dir>/android-tools/aosp-patches/ with the patches in
# aosp-patches/series, and writes <recipe-dir>/android-tools-aosp-patches.inc
# listing them in SRC_URI in series order.
#
# It refuses to run if the recipe's AOSP_PROJECTS differs from the projects
# in scripts/aosp-projects (less those marked workbench-only), or if this
# tree isn't committed.
set -euo pipefail

DEST=$(realpath -m "${1:?usage: $0 <recipe-dir>}")
ROOT=$(git -C "$(dirname "$(realpath "$0")")" rev-parse --show-toplevel)
cd "$ROOT"

if [ -n "$(git status --porcelain)" ]; then
  echo "$0: working tree isn't clean; commit first" >&2
  exit 1
fi

shopt -s nullglob
RECIPES=("$DEST"/android-tools_*.bb)
[ ${#RECIPES[@]} -eq 1 ] || { echo "$0: expected one android-tools_*.bb in $DEST" >&2; exit 1; }

# AOSP_PROJECTS = " a b c " (possibly over several lines)
recipe_projects=$(python3 -I - "${RECIPES[0]}" <<'EOF'
import re, sys
m = re.search(r'^AOSP_PROJECTS\s*=\s*"(.*?)"', open(sys.argv[1]).read(), re.S | re.M)
print("\n".join(sorted(m.group(1).replace("\\", " ").split())) if m else "")
EOF
)
workbench_projects=$(awk '!/^#/ && NF && $3 != "workbench-only" {print $1}' scripts/aosp-projects | sort)
if [ "$recipe_projects" != "$workbench_projects" ]; then
  echo "$0: recipe AOSP_PROJECTS and scripts/aosp-projects differ:" >&2
  diff <(echo "$recipe_projects") <(echo "$workbench_projects") | sed 's/^< /  recipe only:    /; s/^> /  workbench only: /' | grep -v '^[0-9]' >&2
  exit 1
fi

DESC=$(git describe --tags --always HEAD)
FILES="$DEST/android-tools"
INC="$DEST/android-tools-aosp-patches.inc"

mapfile -t PATCHES < <(grep -v -e '^#' -e '^$' aosp-patches/series)
for p in "${PATCHES[@]}"; do
  grep -q '^Upstream-Status:' "aosp-patches/$p" || { echo "$0: $p has no Upstream-Status" >&2; exit 1; }
done

rm -rf "$FILES/build" "$FILES/aosp-patches"
mkdir -p "$FILES/build" "$FILES/aosp-patches"
git archive HEAD build | tar -x -C "$FILES"
for p in "${PATCHES[@]}"; do
  cp "aosp-patches/$p" "$FILES/aosp-patches/"
done

{
  echo "# Generated by scripts/export-oe-patches.sh from android-platform-tools-aosp"
  echo "# $DESC. Don't edit; change the patches there and re-export."
  echo
  echo "SRC_URI += \" \\"
  for p in "${PATCHES[@]}"; do
    echo "    file://aosp-patches/$p \\"
  done
  echo "\""
} > "$INC"

echo "Exported build/ and ${#PATCHES[@]} patches at $DESC to $DEST"
