#!/usr/bin/env bash
# Export the patch stack for the OE android-tools recipe.
#
# usage: scripts/export-oe-patches.sh <recipe-dir>
#
# <recipe-dir> is the directory holding android-tools_<ver>.bb. This replaces
# <recipe-dir>/android-tools/aosp-patches/ with the patches in
# aosp-patches/series and writes <recipe-dir>/android-tools-aosp-patches.inc,
# which pins SRCREV to this repo's HEAD and adds the patches to SRC_URI in
# series order. Run it from a clean checkout of the commit the recipe should
# build.
set -euo pipefail

DEST=${1:?usage: $0 <recipe-dir>}
ROOT=$(git rev-parse --show-toplevel)
cd "$ROOT"

if [ -n "$(git status --porcelain)" ]; then
  echo "$0: working tree isn't clean; commit first" >&2
  exit 1
fi

REV=$(git rev-parse HEAD)
DESC=$(git describe --tags --always HEAD)
PATCHDIR="$DEST/android-tools/aosp-patches"
INC="$DEST/android-tools-aosp-patches.inc"

mapfile -t PATCHES < <(grep -v -e '^#' -e '^$' aosp-patches/series)

for p in "${PATCHES[@]}"; do
  grep -q '^Upstream-Status:' "aosp-patches/$p" || { echo "$0: $p has no Upstream-Status" >&2; exit 1; }
done

rm -rf "$PATCHDIR"
mkdir -p "$PATCHDIR"
for p in "${PATCHES[@]}"; do
  cp "aosp-patches/$p" "$PATCHDIR/"
done

{
  echo "# Generated by scripts/export-oe-patches.sh from android-platform-tools-aosp"
  echo "# $DESC. Don't edit; change the patches there and re-export."
  echo
  echo "SRCREV = \"$REV\""
  echo
  echo "SRC_URI += \" \\"
  for p in "${PATCHES[@]}"; do
    echo "    file://aosp-patches/$p \\"
  done
  echo "\""
} > "$INC"

echo "Exported ${#PATCHES[@]} patches at $DESC to $DEST"
